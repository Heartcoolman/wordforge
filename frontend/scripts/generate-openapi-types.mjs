import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../..');
const specPath = resolve(repoRoot, 'docs/openapi.yaml');
const outputPath = resolve(repoRoot, 'frontend/src/types/openapi.ts');

const methods = new Set(['get', 'post', 'put', 'patch', 'delete']);
const spec = readFileSync(specPath, 'utf8').split(/\r?\n/);
const paths = [];
let inPaths = false;
let currentPath = null;
let currentMethod = null;

for (const line of spec) {
  if (line === 'paths:') {
    inPaths = true;
    continue;
  }

  if (inPaths && line.length > 0 && !line.startsWith(' ') && line !== 'paths:') {
    break;
  }

  if (!inPaths) continue;

  const pathMatch = line.match(/^  (\/[^:]+):\s*$/);
  if (pathMatch) {
    currentPath = { path: pathMatch[1], methods: [] };
    paths.push(currentPath);
    currentMethod = null;
    continue;
  }

  const methodMatch = line.match(/^    ([a-z]+):\s*$/);
  if (methodMatch && methods.has(methodMatch[1]) && currentPath) {
    currentMethod = { method: methodMatch[1], response: 'unknown' };
    currentPath.methods.push(currentMethod);
    continue;
  }

  const responseTypeMatch = line.match(/^      x-frontend-response-type:\s*(.+?)\s*$/);
  if (responseTypeMatch && currentMethod) {
    currentMethod.response = responseTypeMatch[1].replace(/^["']|["']$/g, '');
  }
}

if (paths.length === 0) {
  throw new Error(`No paths found in ${specPath}`);
}

const lines = [
  '// Generated from docs/openapi.yaml by `npm run generate:openapi-types`.',
  '// Do not edit this file by hand.',
  '',
  'export interface OpenApiPaths {',
];

for (const entry of paths) {
  lines.push(`  '${entry.path}': {`);
  for (const operation of entry.methods) {
    lines.push(`    ${operation.method}: { response: ${operation.response} };`);
  }
  lines.push('  };');
}

lines.push('}', '', 'export type OpenApiPath = keyof OpenApiPaths;', '');

writeFileSync(outputPath, lines.join('\n'));
console.log(`Generated ${outputPath}`);
